// Packs the v3 players (art-src/blender/players/out/, from art-src/blender/players/build_players.py) into
// assets/players-<tier>.js: classic scripts that set window.DS_PLAYERS = {tier, meta, glb: {build: base64 GLB},
// skin: {light, dark: WebP data URLs}}, so they load from file:// too. The game loads one after it is up
// (render3d.js loadPlayerPack). Run tools/pack-models.mjs after this: it lists the packs for the game.
//
//   node tools/pack-players.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = path.join(root, 'art-src', 'blender', 'players', 'out');
const meta = JSON.parse(fs.readFileSync(path.join(src, 'meta.json'), 'utf8'));
const SKIN = { high: 2048, medium: 1024 };
for (const tier of ['medium', 'high']) {
  const glb = {};
  for (const b of Object.keys(meta.variants)) {
    const f = path.join(src, `body-${b}-${tier}.glb`);
    if (fs.existsSync(f)) glb[b] = fs.readFileSync(f).toString('base64');
  }
  const skin = {};
  for (const k of ['light', 'dark']) {
    const f = path.join(src, `skin-${k}-${SKIN[tier]}.webp`);
    if (fs.existsSync(f)) skin[k] = `data:image/webp;base64,${fs.readFileSync(f).toString('base64')}`;
  }
  // cloth detail normal map (high tier only)
  const fab = path.join(src, 'fabric-nor-512.webp');
  if (tier === 'high' && fs.existsSync(fab)) skin.fabric = `data:image/webp;base64,${fs.readFileSync(fab).toString('base64')}`;
  const m = { variants: Object.fromEntries(Object.entries(meta.variants).map(([b, v]) => [b, { hipHeight: v.hipHeight, height: v.height, chest: v.chest, tris: v.tris }])), lods: meta.lods };
  const js = `// Generated by tools/pack-players.mjs from art-src/blender/players/out/. Do not edit.\nwindow.DS_PLAYERS = ${JSON.stringify({ tier, meta: m, glb, skin })};\n`;
  fs.writeFileSync(path.join(root, 'assets', `players-${tier}.js`), js);
  console.log(`assets/players-${tier}.js  ${(js.length / 1048576).toFixed(2)} MB  (${Object.keys(glb).join(', ')}; skin ${Object.keys(skin).join(', ')})`);
}
