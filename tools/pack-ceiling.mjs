// Packs the performance-ceiling ladder (art-src/ceiling/*.glb, from art-src/blender/ceiling.py) into
// assets/ceiling-<name>.js, each a classic script that sets window.DS_MODELS.player. The game loads one with
// ?players=ceiling-<name>. Measurement only: these files are git-ignored and never shipped.
//
//   node tools/pack-ceiling.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = path.join(root, 'art-src', 'ceiling');
for (const f of fs.readdirSync(src).filter((f) => f.endsWith('.glb')).sort()) {
  const b = fs.readFileSync(path.join(src, f));
  const name = `ceiling-${f.replace(/^player-/, '').replace(/\.glb$/, '')}`;
  fs.writeFileSync(path.join(root, 'assets', `${name}.js`), `// Generated by tools/pack-ceiling.mjs. Do not edit.\nwindow.DS_MODELS = { player: '${b.toString('base64')}' };\n`);
  console.log(`${name}  ${(b.length / 1024).toFixed(0)} KB`);
}
