// Packs the Blender exports into assets/models.js, a classic script that sets window.DS_MODELS to
// base64 GLB strings, so the 3D view loads models from file:// too (fetch() of local files fails there).
//
//   node tools/pack-models.mjs
//
// Sources: art-src/blender/*.glb, built by the scripts beside them (see art-src/blender/*.py).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const src = path.join(here, '..', 'art-src', 'blender');
const out = path.join(here, '..', 'assets', 'models.js');
const names = fs.readdirSync(src).filter((f) => f.endsWith('.glb')).sort();
let js = '// Generated by tools/pack-models.mjs from art-src/blender/*.glb. Do not edit.\nwindow.DS_MODELS = {\n';
for (const f of names) {
  const b = fs.readFileSync(path.join(src, f));
  js += `  ${JSON.stringify(f.replace(/\.glb$/, ''))}: '${b.toString('base64')}',\n`;
  console.log(`${f}  ${(b.length / 1024).toFixed(1)} KB`);
}
js += '};\n';
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, js);
console.log(`${path.relative(process.cwd(), out)}  ${(js.length / 1024).toFixed(1)} KB`);

// The painted art as data URLs too (assets/art.js), for file:// where images from local files taint
// canvases and WebGL rejects them. Over http the game loads the smaller assets/*.webp instead.
const man = JSON.parse(fs.readFileSync(path.join(here, '..', 'assets', 'manifest.json'), 'utf8'));
let art = '// Generated by tools/pack-models.mjs from assets/*.webp (used only from file://). Do not edit.\nwindow.DS_ART = {\n';
for (const name of Object.keys(man).sort()) {
  const b = fs.readFileSync(path.join(here, '..', 'assets', `${name}.webp`));
  art += `  ${JSON.stringify(name)}: 'data:image/webp;base64,${b.toString('base64')}',\n`;
}
art += '};\n';
fs.writeFileSync(path.join(here, '..', 'assets', 'art.js'), art);
console.log(`assets/art.js  ${(art.length / 1024).toFixed(1)} KB (${Object.keys(man).length} paintings)`);
